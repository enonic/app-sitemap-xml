    @Override
    public void onEvent( final Event event )
    {
        final String type = event.getType();
        final Set<List<String>> changed = new LinkedHashSet<>();
        if ( type.startsWith( "node." ) )
        {
            final Object data = event.getData().get( "nodes" );
            if ( data instanceof List<?> || event.getData().containsKey( "repo" ) )
            {
                for ( final Object node : data instanceof List<?> nodes ? nodes : List.of( event.getData() ) )
                {
                    if ( node instanceof Map<?, ?> map && map.get( "repo" ) instanceof String repo &&
                        map.get( "branch" ) instanceof String branch )
                    {
                        if ( repo.equals( RepositorySitemapStore.REPOSITORY.toString() ) )
                        {
                            if ( !event.isLocalOrigin() && map.get( "path" ) instanceof String path )
                            {
                                storedElsewhere( path.substring( path.lastIndexOf( '/' ) + 1 ), type );
                            }
                        }
                        else
                        {
                            changed.add( List.of( repo, branch ) );
                        }
                    }
                }
            }
        }
        else if ( type.startsWith( "repository." ) && event.getData().get( "id" ) instanceof String repo &&
            !repo.equals( RepositorySitemapStore.REPOSITORY.toString() ) )
        {
            changed.add( List.of( repo ) );
        }
        final Instant now = clock.instant();
        changed.forEach(
            change -> contentChanged( change.get( 0 ), change.size() > 1 ? change.get( 1 ) : null, event.isLocalOrigin(), now ) );
    }

    private Entry entry( final Key key )
    {
        return entries.computeIfAbsent( key, k -> {
            keys.put( k.id(), k );
            return new Entry();
        } );
    }

    /**
     * The stored sitemap of the key as this node knows it, read from the store the first time and after another node stored it.
     */
    private SitemapStore.@Nullable Stored current( final Key key, final Entry entry )
    {
        if ( entry.loaded )
        {
            return entry.stored;
        }
        synchronized ( entry )
        {
            if ( !entry.loaded )
            {
                final SitemapStore.Stored stored = store.load( key.id() );
                entry.stored = stored;
                entry.sitemapChanges = entry.changes;
                entry.loaded = true;
                if ( stored != null && stored.sitemap() != null )
                {
                    entry.ready.complete( stored.sitemap() );
                }
            }
            return entry.stored;
        }
    }

    /**
     * Whether a request for the stored sitemap should start generating it again. A regen sitemap is left to the node where its
     * content changed, unless it was generated before the cluster started or that node failed to generate it: no newer version arrived
     * while the change, as marked in the store or seen by this node, is overdue.
     */
    private boolean shouldRegenerate( final Entry entry, final SitemapStore.Stored stored, final Instant now )
    {
        final Pending pending = entry.pending;
        if ( pending != null && pending.startsWithin( regenerationDelay ) )
        {
            return false;
        }
        final Instant validUntil = stored.validUntil();
        final Instant generatedAt = stored.generatedAt();
        if ( validUntil != null && !now.isBefore( validUntil ) || generatedAt != null && generatedAt.isBefore( clusterStarted ) )
        {
            return true;
        }
        final Instant obsolete = stored.obsolete();
        if ( stored.regen() )
        {
            final Instant seen = entry.sitemapChanges != entry.changes ? entry.firstChangedAt : null;
            return obsolete != null && overdue( obsolete, now ) || seen != null && overdue( seen, now );
        }
        return obsolete != null || entry.sitemapChanges != entry.changes;
    }

    /**
     * Whether a content change at the given time should have been included by a generation in the background by now.
     */
    private boolean overdue( final Instant changedAt, final Instant now )
    {
        return changedAt.plus( regenerationDelay ).plus( STALE_GENERATION ).isBefore( now );
    }

    /**
     * Whether a stored sitemap needs no generation: its content did not change, it is not past a scheduled change and it was generated
     * since the cluster started.
     */
    private boolean isUpToDate( final SitemapStore.Stored stored, final Instant now, final @Nullable Instant changedAt )
    {
        final Instant validUntil = stored.validUntil();
        final Instant generatedAt = stored.generatedAt();
        final Instant startedAt = stored.startedAt();
        return stored.sitemap() != null && stored.obsolete() == null && ( validUntil == null || now.isBefore( validUntil ) ) &&
            generatedAt != null && !generatedAt.isBefore( clusterStarted ) &&
            ( changedAt == null || startedAt != null && startedAt.isAfter( changedAt ) );
    }

    /**
     * Another node stored, replaced or deleted a sitemap: read it again when it is next requested, or now if requests are waiting for it.
     */
    private void storedElsewhere( final String id, final String type )
    {
        released( id );
        final Key key = keys.get( id );
        final Entry entry = key == null ? null : entries.get( key );
        if ( entry == null )
        {
            return;
        }
        if ( type.equals( "node.deleted" ) )
        {
            final SitemapStore.Stored stored = entry.stored;
            remove( key, entry, stored == null || stored.sitemap() == null
                ? new IllegalStateException( "Sitemap could not be generated" )
                : new CancellationException( "Sitemap removed" ) );
            return;
        }
        entry.loaded = false;
        if ( !entry.ready.isDone() )
        {
            execute( () -> current( key, entry ) );
        }
    }

    /**
     * Content changed in the repository, and branch if not null. All nodes take note for the sitemaps they know; the node where it changed
     * marks all sitemaps of the project as obsolete in the store and generates those in the background that are generated so.
     */
    private void contentChanged( final String repositoryId, final @Nullable String branch, final boolean localOrigin,
                                 final Instant changedAt )
    {
        entries.forEach( ( key, entry ) -> {
            if ( key.repositoryId().equals( repositoryId ) && ( branch == null || key.branch().equals( branch ) ) )
            {
                synchronized ( entry )
                {
                    if ( entry.changes == entry.sitemapChanges )
                    {
                        entry.firstChangedAt = changedAt;
                    }
                    entry.changes++;
                    entry.changedAt = changedAt;
                }
            }
        } );
        if ( localOrigin )
        {
            final List<String> scope = branch == null ? List.of( repositoryId ) : List.of( repositoryId, branch );
            final boolean[] first = {false};
            unmarked.compute( scope, ( changed, latest ) -> {
                first[0] = latest == null;
                return latest == null || changedAt.isAfter( latest ) ? changedAt : latest;
            } );
            if ( first[0] )
            {
                schedule( () -> {
                    final Instant latest = unmarked.remove( scope );
                    if ( latest != null )
                    {
                        markObsolete( repositoryId, branch, latest );
                    }
                }, regenerationDelay );
            }
        }
    }

    /**
     * Marks the sitemaps of the repository, and branch if not null, obsolete in the store and generates the regen ones. Runs
     * {@link #regenerationDelay} after the first of the changes it covers, so that a flood of changes makes one pass, and one generation,
     * per delay; changes arriving meanwhile wait for the next pass.
     */
    private void markObsolete( final String repositoryId, final @Nullable String branch, final Instant changedAt )
    {
        for ( final SitemapStore.Stored stored : store.find( repositoryId, branch ) )
        {
            final Instant startedAt = stored.startedAt();
            if ( startedAt != null && startedAt.isAfter( changedAt ) )
            {
                continue;
            }
            store.markObsolete( stored, changedAt );
            if ( stored.regen() )
            {
                final Entry entry = entry( stored.key() );
                entry.regen = true;
                generate( stored.key(), entry, Duration.ZERO, true, changedAt );
            }
        }
    }

    /**
     * Submits a generation task for the entry after the given delay, unless one is already due by then. Without {@code force}, a task
     * submitted less than {@link #SUBMIT_INTERVAL} ago is not submitted again unless the content changed since: it ends at once when
     * another node is generating the sitemap, so requests would otherwise submit one each.
     */
    private void generate( final Key key, final Entry entry, final Duration delay, final boolean force, final @Nullable Instant changedAt )
    {
        synchronized ( entry )
        {
            final Pending current = entry.pending;
            if ( current != null )
            {
                if ( current.startsWithin( delay ) )
                {
                    current.changed( changedAt );
                    return;
                }
                current.cancel();
                entry.pending = null;
            }
            final Instant submitted = entry.submitted;
            if ( stopped || !force && submitted != null && submitted.plus( SUBMIT_INTERVAL ).isAfter( clock.instant() ) &&
                ( changedAt == null || !changedAt.isAfter( submitted ) ) )
            {
                return;
            }
            if ( delay.isNegative() || delay.isZero() )
            {
                submit( key, entry, changedAt );
                return;
            }
            final Pending pending = new Pending( key, entry, delay, changedAt );
            entry.pending = pending;
            try
            {
                pending.future = scheduler.schedule( pending, delay.toMillis(), TimeUnit.MILLISECONDS );
            }
            catch ( RejectedExecutionException e )
            {
                entry.pending = null;
            }
        }
    }

    private void submit( final Key key, final Entry entry, final @Nullable Instant changedAt )
    {
        if ( stopped )
        {
            return;
        }
        entry.submitted = clock.instant();
        try
        {
            tasks.submit( key, entry.regen, changedAt );
        }
        catch ( RuntimeException e )
        {
            entry.submitted = null;
            LOG.warn( "Could not submit generation of sitemap {}", key, e );
            if ( !entry.ready.isDone() )
            {
                remove( key, entry, e );
            }
        }
    }

    /**
     * Generates and stores the sitemap of the key, claimed by the given generation.
     */
    private void generateAndStore( final Key key, final boolean regen, final String generation,
                                   final SitemapStore.@Nullable Stored previous, final Instant startedAt,
                                   final @Nullable ProgressReporter progress )
    {
        report( progress, "Reading contents" );
        final String id = key.id();
        final Entry local = entries.get( key );
        final long changes = local == null ? -1 : local.changes;
        try (Sitemap.Builder builder = Sitemap.builder( temp.resolve( UUID.randomUUID().toString() ), key.params() ))
        {
            final Instant validUntil = ContextBuilder.create()
                .repositoryId( key.repositoryId() )
                .branch( key.branch() )
                .authInfo( authInfo( key ) )
                .build()
                .callWith( () -> sources.apply( key ).write( sink( builder, progress ), () -> stopped ) );
            if ( stopped )
            {
                throw new CancellationException();
            }
            final Sitemap generated = builder.build( previous == null ? null : previous.sitemap(), clock.instant() );
            report( progress, "Storing " + summary( generated ) );
            final SitemapStore.Stored stored;
            try
            {
                stored = store.save( id, key, regen, generated, validUntil, startedAt, clock.instant() );
            }
            finally
            {
                generated.delete();
            }
            published( key, stored, changes );
            evictOverflow( key );
            deleteOld();
            LOG.debug( "Generated sitemap {}", key );
            report( progress, "Generated " + summary( generated ) );
            if ( regen && validUntil != null )
            {
                final Entry entry = entry( key );
                entry.regen = true;
                generate( key, entry, Duration.between( clock.instant(), validUntil ), true, null );
            }
        }
        catch ( CancellationException e )
        {
            release( key, generation );
            LOG.debug( "Generation of sitemap {} halted", key );
            report( progress, "Generation halted" );
        }
        catch ( RuntimeException e )
        {
            release( key, generation );
            failed( key, e );
            report( progress, "Generation failed: " + e.getMessage() );
        }
    }

    private static SitemapSink sink( final Sitemap.Builder builder, final @Nullable ProgressReporter progress )
    {
        return new SitemapSink()
        {
            @Override
            public void accept( final SitemapEntry entry )
            {
                builder.add( entry );
            }

            @Override
            public void progress( final long read, final long total )
            {
                if ( progress != null )
                {
                    progress.progress( ProgressReportParams.create( (int) Math.min( read, Integer.MAX_VALUE ),
                                                                    (int) Math.min( total, Integer.MAX_VALUE ) ).build() );
                }
            }
        };
    }

    private static String summary( final Sitemap sitemap )
    {
        return sitemap.size() + " URLs in " + sitemap.fileCount() + ( sitemap.fileCount() == 1 ? " file" : " files" );
    }

    private static void report( final @Nullable ProgressReporter progress, final String message )
    {
        if ( progress != null )
        {
            progress.progress( ProgressReportParams.create( message ).build() );
        }
    }

    /**
     * Waits until the generation running for the sitemap ends: its store event, or a while, as the end of a failed generation is not
     * announced to other nodes.
     */
    private void awaitRelease( final String id )
    {
        try
        {
            releases.computeIfAbsent( id, ignored -> new CompletableFuture<>() ).get( RELEASE_POLL.toMillis(), TimeUnit.MILLISECONDS );
        }
        catch ( TimeoutException | ExecutionException e )
        {
            LOG.debug( "Sitemap {} still generated elsewhere", id );
        }
        catch ( InterruptedException e )
        {
            Thread.currentThread().interrupt();
            throw new CancellationException( "Interrupted" );
        }
    }

    private void released( final String id )
    {
        final CompletableFuture<Void> release = releases.remove( id );
        if ( release != null )
        {
            release.complete( null );
        }
    }

    private void release( final Key key, final String generation )
    {
        try
        {
            store.release( key.id(), generation );
        }
        catch ( RuntimeException e )
        {
            LOG.debug( "Could not release sitemap {}", key, e );
        }
    }

    /**
     * Updates what this node knows of the sitemap after storing it, and answers the requests waiting for it.
     *
     * @param changes the content changes this node had seen when the generation started, or -1 to keep what it knows
     */
    private void published( final Key key, final SitemapStore.Stored stored, final long changes )
    {
        final Entry entry = entries.get( key );
        if ( entry == null )
        {
            return;
        }
        synchronized ( entry )
        {
            entry.stored = stored;
            entry.loaded = true;
            if ( changes >= 0 )
            {
                entry.sitemapChanges = changes;
                entry.firstChangedAt = changes == entry.changes ? null : entry.changedAt;
            }
        }
        entry.ready.complete( stored.sitemap() );
    }

    private void failed( final Key key, final RuntimeException e )
    {
        final Entry entry = entries.get( key );
        final SitemapStore.Stored stored = entry == null ? null : entry.stored;
        if ( entry != null && ( stored == null || stored.sitemap() == null ) )
        {
            remove( key, entry, e );
        }
        else
        {
            LOG.warn( "Could not generate sitemap for {} {} {}", key.repositoryId(), key.branch(), key.params().sitePath(), e );
        }
    }

    private void remove( final Key key, final Entry entry )
    {
        remove( key, entry, new CancellationException( "Sitemap removed" ) );
    }

    /**
     * Removes the entry before failing requests waiting for it, so a request after them starts over with a new entry.
     */
    private void remove( final Key key, final Entry entry, final RuntimeException cause )
    {
        if ( entries.remove( key, entry ) )
        {
            keys.remove( key.id(), key );
            synchronized ( entry )
            {
                final Pending pending = entry.pending;
                if ( pending != null )
                {
                    pending.cancel();
                    entry.pending = null;
                }
            }
            entry.ready.completeExceptionally( cause );
            LOG.debug( "Removed sitemap {}", key );
        }
    }

    /**
     * Deletes stored sitemaps of the site and principals of the given key beyond {@value #MAX_PER_SITE}: a site is requested through a
     * few hosts, ports and schemes, but they come from the request and can be made up. Sitemaps whose site URL names a port go first,
     * then the least recently requested.
     */
    private void evictOverflow( final Key key )
    {
        final List<SitemapStore.Stored> site = store.ofSite( key );
        site.stream()
            .filter( stored -> stored.sitemap() != null )
            .sorted( EVICTION_ORDER )
            .limit( Math.max( 0, site.size() - MAX_PER_SITE ) )
            .toList()
            .forEach( this::delete );
    }

    /**
     * Deletes stored sitemaps generated on request more than {@link #RETENTION} ago, unless they are being generated: sitemaps of
     * principals no request has any longer, after a change of roles or groups, of deleted users, or of hosts no longer used. A sitemap
     * still requested is generated again on its next request. Regen sitemaps are kept, as they are public and do not depend on the
     * request host.
     */
    private void deleteOld()
    {
        final Instant now = clock.instant();
        store.generatedBefore( now.minus( RETENTION ) ).stream().filter( stored -> !stored.regen() ).filter( stored -> {
            final SitemapStore.Generating generating = stored.generating();
            return generating == null || !generating.since().plus( STALE_GENERATION ).isAfter( now );
        } ).forEach( this::delete );
    }

    private void delete( final SitemapStore.Stored stored )
    {
        store.delete( stored.id() );
        final Entry entry = entries.get( stored.key() );
        if ( entry != null )
        {
            remove( stored.key(), entry );
        }
    }

    private void schedule( final Runnable runnable, final Duration delay )
    {
        if ( delay.isNegative() || delay.isZero() )
        {
            execute( runnable );
            return;
        }
        try
        {
            scheduler.schedule( () -> {
                try
                {
                    runnable.run();
                }
                catch ( RuntimeException e )
                {
                    LOG.warn( "Could not update sitemaps", e );
                }
            }, delay.toMillis(), TimeUnit.MILLISECONDS );
        }
        catch ( RejectedExecutionException e )
        {
            LOG.debug( "Sitemaps stopped", e );
        }
    }

    private void execute( final Runnable runnable )
    {
        try
        {
            scheduler.execute( () -> {
                try
                {
                    runnable.run();
                }
                catch ( RuntimeException e )
                {
                    LOG.warn( "Could not update sitemaps", e );
                }
            } );
        }
        catch ( RejectedExecutionException e )
        {
            LOG.debug( "Sitemaps stopped", e );
        }
    }

    /**
     * Waits for the entry's sitemap, generated here or by another node. Returns null when it did not come in time: it is then requested
     * again.
     */
    private @Nullable Sitemap await( final Entry entry )
    {
        try
        {
            return entry.ready.get( STALE_GENERATION.toMillis(), TimeUnit.MILLISECONDS );
        }
        catch ( TimeoutException e )
        {
            entry.loaded = false;
            entry.submitted = null;
            return null;
        }
        catch ( ExecutionException e )
        {
            if ( e.getCause() instanceof RuntimeException cause )
            {
                throw cause;
            }
            throw new CompletionException( e.getCause() );
        }
        catch ( InterruptedException e )
        {
            Thread.currentThread().interrupt();
            throw new CancellationException( "Interrupted" );
        }
    }

    private static AuthenticationInfo authInfo( final Key key )
    {
        return AuthenticationInfo.copyOf( AuthenticationInfo.unAuthenticated() )
            .principals( key.principals().stream().map( PrincipalKey::from ).toList() )
            .build();
    }

    /**
     * Writes the entries of a sitemap.
     */
    @FunctionalInterface
    public interface Source
    {
        /**
         * @param sink      receives the entries
         * @param cancelled returns true once the generation is halted
         * @return when the sitemap must be generated again, or null
         */
        @Nullable Instant write( SitemapSink sink, BooleanSupplier cancelled );
    }

    /**
     * Submits generation tasks.
     */
    @FunctionalInterface
    interface Tasks
    {
        void submit( Key key, boolean regen, @Nullable Instant changedAt );

        /**
         * Submits the {@code generate} task of this app, which XP may offload to another cluster node.
         */
        static Tasks of( final TaskService taskService )
        {
            return ( key, regen, changedAt ) -> {
                final PropertyTree data = new PropertyTree();
                try
                {
                    data.setString( "key", MAPPER.writeValueAsString( key.store() ) );
                }
                catch ( JsonProcessingException e )
                {
                    throw new IllegalStateException( e );
                }
                data.setBoolean( "regen", regen );
                if ( changedAt != null )
                {
                    data.setString( "changedAt", changedAt.toString() );
                }
                taskService.submitTask( SubmitTaskParams.create()
                                            .descriptorKey( DescriptorKey.from( APPLICATION, TASK ) )
                                            .name( "Sitemap of " + key.repositoryId() + " " +
                                                       ( key.params().sitePath().isEmpty() ? "/" : key.params().sitePath() ) + " " +
                                                       key.params().siteUrl() )
                                            .data( data )
                                            .build() );
            };
        }
    }

    public record Key(String repositoryId, String branch, Set<String> principals, SitemapParams params)
    {
        public Key
        {
            principals = Set.copyOf( principals );
        }

        /**
         * A digest of the key, naming its sitemap in the store.
         */
        String id()
        {
            try
            {
                final byte[] json = MAPPER.writeValueAsString( store() ).getBytes( StandardCharsets.UTF_8 );
                return HexFormat.of().formatHex( MessageDigest.getInstance( "SHA-256" ).digest( json ) );
            }
            catch ( JsonProcessingException | NoSuchAlgorithmException e )
            {
                throw new IllegalStateException( e );
            }
        }

        ObjectNode store()
        {
            final ObjectNode key = JsonNodeFactory.instance.objectNode();
            key.put( "repository", repositoryId );
            key.put( "branch", branch );
            final ArrayNode principals = key.putArray( "principals" );
            new TreeSet<>( this.principals ).forEach( principals::add );
            key.put( "sitePath", params.sitePath() );
            key.put( "siteUrl", params.siteUrl() );
            final ArrayNode contentTypes = key.putArray( "contentTypes" );
            for ( final ContentTypeSetting setting : params.contentTypes() )
            {
                contentTypes.addObject()
                    .put( "contentType", setting.contentType() )
                    .put( "changefreq", setting.changefreq() )
                    .put( "priority", setting.priority() );
            }
            final ArrayNode ignorePatterns = key.putArray( "ignorePatterns" );
            params.ignorePatterns().forEach( ignorePatterns::add );
            return key;
        }

        static Key restore( final JsonNode key )
        {
            final List<ContentTypeSetting> contentTypes = new ArrayList<>();
            for ( final JsonNode setting : key.required( "contentTypes" ) )
            {
                contentTypes.add( new ContentTypeSetting( setting.required( "contentType" ).asText(),
                                                          setting.required( "changefreq" ).asText(),
                                                          setting.required( "priority" ).asText() ) );
            }
            final SitemapParams params =
                new SitemapParams( key.required( "sitePath" ).asText(), key.required( "siteUrl" ).asText(), contentTypes,
                                   strings( key.required( "ignorePatterns" ) ) );
            return new Key( key.required( "repository" ).asText(), key.required( "branch" ).asText(),
                            Set.copyOf( strings( key.required( "principals" ) ) ), params );
        }

        private static List<String> strings( final JsonNode array )
        {
            final List<String> strings = new ArrayList<>();
            for ( final JsonNode item : array )
            {
                strings.add( item.asText() );
            }
            return strings;
        }
    }

    /**
     * A generation task to submit after a delay.
     */
    private final class Pending
        implements Runnable
    {
        final Key key;

        final Entry entry;

        final long due;

        volatile @Nullable ScheduledFuture<?> future;

        /**
         * The latest content change the generation must include.
         */
        volatile @Nullable Instant changedAt;

        Pending( final Key key, final Entry entry, final Duration delay, final @Nullable Instant changedAt )
        {
            this.key = key;
            this.entry = entry;
            this.due = System.nanoTime() + delay.toNanos();
            this.changedAt = changedAt;
        }

        void changed( final @Nullable Instant at )
        {
            final Instant current = changedAt;
            if ( at != null && ( current == null || at.isAfter( current ) ) )
            {
                changedAt = at;
            }
        }

        boolean startsWithin( final Duration delay )
        {
            return due - System.nanoTime() <= delay.toNanos();
        }

        void cancel()
        {
            final ScheduledFuture<?> scheduled = future;
            if ( scheduled != null )
            {
                scheduled.cancel( false );
            }
        }

        @Override
        public void run()
        {
            synchronized ( entry )
            {
                if ( entry.pending != this )
                {
                    return;
                }
                entry.pending = null;
            }
            submit( key, entry, changedAt );
        }
    }

    private static final class Entry
    {
        final CompletableFuture<Sitemap> ready = new CompletableFuture<>();

        volatile boolean regen;

        volatile boolean loaded;

        volatile SitemapStore.@Nullable Stored stored;

        volatile @Nullable Pending pending;

        volatile @Nullable Instant submitted;

        /**
         * Number of changes of the content seen by this node, and the number the stored sitemap includes.
         */
        volatile long changes;

        volatile long sitemapChanges;

        volatile @Nullable Instant changedAt;

        /**
         * When this node saw the first content change the stored sitemap does not include: a background sitemap is generated again on
         * request when the node where the content changed did not do it in time.
         */
        volatile @Nullable Instant firstChangedAt;
    }
