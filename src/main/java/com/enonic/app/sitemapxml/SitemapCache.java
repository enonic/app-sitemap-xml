    /**
     * When the first node of the cluster that is running now started: sitemaps generated before were generated while changes may have
     * gone unnoticed. Kept in a shared map, which lives as long as any cluster node does.
     */
    private static Instant clusterStarted( final SharedMapService sharedMapService )
    {
        final String now = Instant.now().toString();
        final SharedMap<String, String> map = sharedMapService.getSharedMap( "com.enonic.app.sitemapxml" );
        final String started = map.modify( "started", value -> value != null ? value : now );
        return Instant.parse( started != null ? started : now );
    }

    /**
     * Stops generating, and waits for generations running on this node to halt. Generated sitemaps stay in the store.
     */
    @Deactivate
    public void deactivate()
    {
        stopped = true;
        for ( final Entry entry : entries.values() )
        {
            final Pending pending = entry.pending;
            if ( pending != null )
            {
                pending.cancel();
            }
            entry.ready.completeExceptionally( new CancellationException( "Sitemaps stopped" ) );
        }
        scheduler.shutdownNow();
        final long deadline = System.nanoTime() + STOP_TIMEOUT.toNanos();
        try
        {
            for ( final CountDownLatch finished : List.copyOf( running ) )
            {
                if ( !finished.await( deadline - System.nanoTime(), TimeUnit.NANOSECONDS ) )
                {
                    LOG.warn( "Sitemap generation still running after {}", STOP_TIMEOUT );
                    break;
                }
            }
        }
        catch ( InterruptedException e )
        {
            Thread.currentThread().interrupt();
        }
        entries.clear();
        keys.clear();
        Sitemap.delete( temp );
    }

    /**
     * Returns the sitemap of the given key, generating it first when it was never generated.
     *
     * @param regen whether the sitemap may be generated again without a request: its URLs do not depend on the request
     * @throws SitemapBusyException when the sitemap was never generated and too many requests are already waiting
     */
    public Sitemap get( final Key key, final boolean regen )
    {
        while ( true )
        {
            final Instant now = clock.instant();
            final Entry entry = entry( key );
            entry.regen = regen;
            final SitemapStore.Stored stored = current( key, entry );
            if ( stored != null && stored.sitemap() != null )
            {
                if ( shouldRegenerate( entry, stored, now ) )
                {
                    generate( key, entry, Duration.ZERO, false, entry.sitemapChanges != entry.changes ? entry.changedAt : null );
                }
                return stored.sitemap();
            }

            if ( stored == null || stored.generating() == null ||
                !stored.generating().since().plus( STALE_GENERATION ).isAfter( now ) )
            {
                generate( key, entry, Duration.ZERO, false, null );
            }
            if ( !waiting.tryAcquire() )
            {
                throw new SitemapBusyException();
            }
            try
            {
                final Sitemap sitemap = await( entry );
                if ( sitemap != null )
                {
                    return sitemap;
                }
            }
            finally
            {
                waiting.release();
            }
        }
    }

    /**
     * Generates and stores the sitemap of the key, unless another node is generating it or it is up to date. Run by the
     * {@code generate} task, on whichever node XP runs it.
     *
     * @param regen   whether the sitemap is generated again without a request
     * @param changedAt  when the node that submitted the task saw its content change, if it did: the sitemap is not up to date unless its
     *                   generation started after that
     * @param progress   receives what the task does and how many contents it has read
     */
    public void runTask( final Key key, final boolean regen, final @Nullable Instant changedAt,
                         final @Nullable ProgressReporter progress )
    {
        if ( stopped )
        {
            return;
        }
        final CountDownLatch finished = new CountDownLatch( 1 );
        running.add( finished );
        final String id = key.id();
        final String generation = member + "/" + UUID.randomUUID();
        try
        {
            while ( !stopped )
            {
                final Instant now = clock.instant();
                final SitemapStore.Stored previous = store.load( id );
                if ( previous != null && isUpToDate( previous, now, changedAt ) )
                {
                    LOG.debug( "Sitemap {} is up to date", key );
                    report( progress, "Sitemap is up to date" );
                    published( key, previous, -1 );
                    return;
                }
                final SitemapStore.Generating generating = previous == null ? null : previous.generating();
                if ( generating != null && !generating.member().equals( generation ) &&
                    generating.since().plus( STALE_GENERATION ).isAfter( now ) )
                {
                    if ( !store.queue( previous, generation, now, STALE_GENERATION ) )
                    {
                        LOG.debug( "Sitemap {} is generated and queued elsewhere", key );
                        report( progress, "Another generation of the sitemap is queued" );
                        return;
                    }
                    report( progress, "Waiting for the running generation of the sitemap" );
                    awaitRelease( id );
                    continue;
                }
                if ( previous == null
                    ? store.claimNew( id, key, regen, generation, now )
                    : store.claim( previous, generation, now, STALE_GENERATION ) )
                {
                    final Semaphore project = projects.computeIfAbsent( key.repositoryId(), repository -> new Semaphore( 1, true ) );
                    project.acquireUninterruptibly();
                    try
                    {
                        generateAndStore( key, regen, generation, previous, now, progress );
                    }
                    finally
                    {
                        project.release();
                        released( id );
                    }
                    return;
                }
            }
        }
        finally
        {
            running.remove( finished );
            finished.countDown();
        }
    }

    /**
     * Generates a sitemap in the calling thread without storing it: its files are deleted once requests are done reading them.
     *
     * @param authInfo the generation runs with these principals
     */
    public Sitemap uncached( final Key key, final AuthenticationInfo authInfo, final Source source )
    {
        try (Sitemap.Builder builder = Sitemap.builder( temp.resolve( UUID.randomUUID().toString() ), key.params() ))
        {
            ContextBuilder.create()
                .repositoryId( key.repositoryId() )
                .branch( key.branch() )
                .authInfo( authInfo )
                .build()
                .callWith( () -> source.write( builder::add, () -> false ) );
            final Sitemap sitemap = builder.build( null, clock.instant() );
            try
            {
                final Runnable delete = sitemap::delete;
                scheduler.schedule( delete, fileRetention.toMillis(), TimeUnit.MILLISECONDS );
            }
            catch ( RejectedExecutionException e )
            {
                sitemap.delete();
            }
            return sitemap;
        }
    }

