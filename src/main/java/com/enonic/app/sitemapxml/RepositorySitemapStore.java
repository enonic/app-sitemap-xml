/**
 * Keeps each sitemap as a node of a transient repository, named by the id of its key, with the sitemap files as attachments. A
 * transient repository is left out of dumps and snapshots, and its old versions are vacuumed early. Its binaries are in XP's blob store,
 * which all cluster nodes share, so a sitemap generated by one node is served by all.
 * <p>
 * Storing a sitemap again creates a new version of its node: requests still reading the files of the previous version keep reading them
 * until the version is vacuumed. Whether the content of the sitemap changed, whether it is being generated and when it was last requested
 * are attributes of the current version, which are changed without creating a version.
 */
final class RepositorySitemapStore
    implements SitemapStore
{
    static final RepositoryId REPOSITORY = RepositoryId.from( "com.enonic.app.sitemapxml" );

    static final String OBSOLETE = "obsolete";

    static final String GENERATING = "generating";

    static final String ACCESSED = "accessed";

    private static final Logger LOG = LoggerFactory.getLogger( RepositorySitemapStore.class );

    private static final ObjectMapper MAPPER = new ObjectMapper();

    private static final PatternIndexConfigDocument INDEX_CONFIG = PatternIndexConfigDocument.create()
        .defaultConfig( IndexConfig.NONE )
        .add( "repository", IndexConfig.MINIMAL )
        .add( "branch", IndexConfig.MINIMAL )
        .add( "sitePath", IndexConfig.MINIMAL )
        .add( "principals", IndexConfig.MINIMAL )
        .build();

    private final NodeService nodeService;

    private final RepositoryService repositoryService;

    private volatile boolean initialized;

    RepositorySitemapStore( final NodeService nodeService, final RepositoryService repositoryService )
    {
        this.nodeService = nodeService;
        this.repositoryService = repositoryService;
    }

    /**
     * Creates the repository unless it exists. Cluster nodes starting at the same time may both try.
     */
    private void initialize()
    {
        context().callWith( () -> {
            if ( repositoryService.get( REPOSITORY ) == null )
            {
                try
                {
                    repositoryService.createRepository( CreateRepositoryParams.create()
                                                            .repositoryId( REPOSITORY )
                                                            .transientFlag( true )
                                                            .rootPermissions( AccessControlList.of( AccessControlEntry.create()
                                                                                                        .principal( RoleKeys.ADMIN )
                                                                                                        .allowAll()
                                                                                                        .build() ) )
                                                            .build() );
                }
                catch ( RepositoryAlreadyExistsException e )
                {
                    LOG.debug( "Repository {} created by another node", REPOSITORY );
                }
            }
            return null;
        } );
    }

    @Override
    public @Nullable Stored load( final String id )
    {
        return call( () -> {
            final Node node = nodeService.getByPath( path( id ) );
            return node == null ? null : toStored( node );
        } );
    }

    @Override
    public boolean claimNew( final String id, final SitemapCache.Key key, final boolean background, final String member,
                             final Instant now )
    {
        return call( () -> {
            try
            {
                nodeService.create( CreateNodeParams.create()
                                        .parent( NodePath.ROOT )
                                        .name( id )
                                        .data( data( key, background, null, null, null, null ) )
                                        .indexConfigDocument( INDEX_CONFIG )
                                        .versionAttributesResolver(
                                            VersionAttributesResolver.of( generating( member, now ) ) )
                                        .refresh( RefreshMode.ALL )
                                        .build() );
                return true;
            }
            catch ( NodeAlreadyExistAtPathException e )
            {
                return false;
            }
        } );
    }

    @Override
    public boolean claim( final Stored stored, final String member, final Instant now, final Duration stale )
    {
        final Generating generating = stored.generating();
        if ( generating != null && !generating.member().equals( member ) && generating.since().plus( stale ).isAfter( now ) )
        {
            return false;
        }
        return call( () -> {
            final Node node = nodeService.getByPath( path( stored.id() ) );
            if ( node == null )
            {
                return false;
            }
            apply( node.getNodeVersionId(), generating( member, now ), null );
            return true;
        } );
    }

    @Override
    public Stored save( final String id, final SitemapCache.Key key, final boolean background, final Sitemap sitemap,
                        final @Nullable Instant validUntil, final Instant startedAt, final Instant now )
    {
        final Map<String, ByteSource> files = sitemap.storedFiles();
        final PropertyTree data = data( key, background, sitemap, validUntil, startedAt, now );
        files.keySet().forEach( name -> data.addBinaryReference( "file", reference( name ) ) );
        final VersionAttributesResolver noAttributes = VersionAttributesResolver.of( Attributes.create().build() );
        return call( () -> {
            final Node existing = nodeService.getByPath( path( id ) );
            final Node node;
            if ( existing == null )
            {
                final CreateNodeParams.Builder create = CreateNodeParams.create()
                    .parent( NodePath.ROOT )
                    .name( id )
                    .data( data )
                    .indexConfigDocument( INDEX_CONFIG )
                    .versionAttributesResolver( noAttributes )
                    .refresh( RefreshMode.ALL );
                files.forEach( ( name, content ) -> create.attachBinary( reference( name ), content ) );
                node = nodeService.create( create.build() );
            }
            else
            {
                final UpdateNodeParams.Builder update = UpdateNodeParams.create()
                    .id( existing.id() )
                    .editor( editable -> editable.data = data )
                    .versionAttributesResolver( noAttributes )
                    .refresh( RefreshMode.ALL );
                files.forEach( ( name, content ) -> update.attachBinary( reference( name ), content ) );
                node = nodeService.update( update.build() );
            }
            return toStored( node );
        } );
    }

    @Override
    public void release( final String id, final String member )
    {
        final Stored stored = load( id );
        if ( stored == null || stored.generating() == null || !stored.generating().member().equals( member ) )
        {
            return;
        }
        if ( stored.sitemap() == null )
        {
            delete( id );
            return;
        }
        call( () -> {
            final Node node = nodeService.getByPath( path( id ) );
            if ( node != null )
            {
                apply( node.getNodeVersionId(), Attributes.create().build(), GENERATING );
            }
            return null;
        } );
    }

    @Override
    public void markObsolete( final Stored stored, final Instant now )
    {
        if ( stored.obsolete() == null )
        {
            applyTo( stored, OBSOLETE, now );
        }
    }

    @Override
    public void touch( final Stored stored, final Instant now )
    {
        applyTo( stored, ACCESSED, now );
    }

    @Override
    public List<Stored> find( final String repositoryId, final @Nullable String branch )
    {
        final NodeQuery.Builder query = NodeQuery.create().parent( NodePath.ROOT ).addQueryFilter( filter( "repository", repositoryId ) );
        if ( branch != null )
        {
            query.addQueryFilter( filter( "branch", branch ) );
        }
        return query( query );
    }

    @Override
    public List<Stored> ofSite( final SitemapCache.Key key )
    {
        return query( NodeQuery.create()
                          .parent( NodePath.ROOT )
                          .addQueryFilter( filter( "repository", key.repositoryId() ) )
                          .addQueryFilter( filter( "branch", key.branch() ) )
                          .addQueryFilter( filter( "sitePath", key.params().sitePath() ) )
                          .addQueryFilter( filter( "principals", principals( key ) ) ) );
    }

    @Override
    public void delete( final String id )
    {
        call( () -> nodeService.delete( DeleteNodeParams.create().nodePath( path( id ) ).refresh( RefreshMode.ALL ).build() ) );
    }

    private List<Stored> query( final NodeQuery.Builder query )
    {
        return call( () -> {
            final List<Stored> stored = new ArrayList<>();
            for ( final Node node : nodeService.getByIds(
                nodeService.findByQuery( query.size( NodeQuery.ALL_RESULTS_SIZE_FLAG ).build() ).getNodeIds() ) )
            {
                stored.add( toStored( node ) );
            }
            return stored;
        } );
    }

    private Stored toStored( final Node node )
        throws JsonProcessingException
    {
        final PropertyTree data = node.data();
        final NodeVersion version = nodeService.getVersion( node.id(), node.getNodeVersionId() );
        final Attributes attributes =
            version == null || version.getAttributes() == null ? Attributes.create().build() : version.getAttributes();
        final SitemapCache.Key key = SitemapCache.Key.restore( MAPPER.readTree( data.getString( "key" ) ) );
        final String description = data.getString( "sitemap" );
        final Sitemap sitemap =
            description == null ? null : Sitemap.restore( files( node.id(), node.getNodeVersionId() ), MAPPER.readTree( description ) );
        final GenericValue generating = attributes.get( GENERATING );
        return new Stored( node.name().toString(), node.getNodeVersionId().toString(), key,
                           Boolean.TRUE.equals( data.getBoolean( "background" ) ), sitemap, data.getInstant( "validUntil" ),
                           data.getInstant( "startedAt" ), data.getInstant( "generatedAt" ), instant( attributes, OBSOLETE ),
                           generating == null ? null : new Generating( generating.property( "member" ).asString(),
                                                                       Instant.parse( generating.property( "since" ).asString() ) ),
                           instant( attributes, ACCESSED ) );
    }

    private Sitemap.FileSource files( final NodeId nodeId, final NodeVersionId versionId )
    {
        return name -> new ByteSource()
        {
            @Override
            public InputStream openStream()
                throws IOException
            {
                return call( () -> nodeService.getBinary( nodeId, versionId, reference( name ) ) ).openStream();
            }
        };
    }

    private static PropertyTree data( final SitemapCache.Key key, final boolean background, final @Nullable Sitemap sitemap,
                                      final @Nullable Instant validUntil, final @Nullable Instant startedAt,
                                      final @Nullable Instant generatedAt )
    {
        final PropertyTree data = new PropertyTree();
        try
        {
            data.setString( "key", MAPPER.writeValueAsString( key.store() ) );
            if ( sitemap != null )
            {
                data.setString( "sitemap", MAPPER.writeValueAsString( sitemap.store() ) );
            }
        }
        catch ( JsonProcessingException e )
        {
            throw new UncheckedIOException( e );
        }
        data.setString( "repository", key.repositoryId() );
        data.setString( "branch", key.branch() );
        data.setString( "sitePath", key.params().sitePath() );
        data.setString( "principals", principals( key ) );
        data.setBoolean( "background", background );
        if ( validUntil != null )
        {
            data.setInstant( "validUntil", validUntil );
        }
        if ( startedAt != null )
        {
            data.setInstant( "startedAt", startedAt );
        }
        if ( generatedAt != null )
        {
            data.setInstant( "generatedAt", generatedAt );
        }
        return data;
    }

    private void applyTo( final Stored stored, final String name, final Instant time )
    {
        call( () -> {
            apply( NodeVersionId.from( stored.version() ),
                   Attributes.create().attribute( name, GenericValue.stringValue( time.toString() ) ).build(), null );
            return null;
        } );
    }

    private void apply( final NodeVersionId versionId, final Attributes add, final @Nullable String remove )
    {
        final ApplyVersionAttributesParams.Builder params =
            ApplyVersionAttributesParams.create().nodeVersionId( versionId ).addAttributes( add );
        if ( remove != null )
        {
            params.removeAttributes( Set.of( remove ) );
        }
        nodeService.applyVersionAttributes( params.build() );
    }

    private static Attributes generating( final String member, final Instant now )
    {
        return Attributes.create()
            .attribute( GENERATING, GenericValue.newObject().put( "member", member ).put( "since", now.toString() ).build() )
            .build();
    }

    private static @Nullable Instant instant( final Attributes attributes, final String name )
    {
        final GenericValue value = attributes.get( name );
        return value == null ? null : Instant.parse( value.asString() );
    }

    private static String principals( final SitemapCache.Key key )
    {
        return String.join( ",", new TreeSet<>( key.principals() ) );
    }

    private static ValueFilter filter( final String field, final String value )
    {
        return ValueFilter.create().fieldName( field ).addValue( ValueFactory.newString( value ) ).build();
    }

    private static BinaryReference reference( final String name )
    {
        return BinaryReference.from( name + Sitemap.GZIP_EXTENSION );
    }

    private static NodePath path( final String id )
    {
        return new NodePath( "/" + id );
    }

    private <T> T call( final Callable<T> callable )
    {
        if ( !initialized )
        {
            synchronized ( this )
            {
                if ( !initialized )
                {
                    initialize();
                    initialized = true;
                }
            }
        }
        return context().callWith( callable );
    }

    private static Context context()
    {
        return ContextBuilder.create()
            .repositoryId( REPOSITORY )
            .branch( RepositoryConstants.MASTER_BRANCH )
            .authInfo( AuthenticationInfo.copyOf( AuthenticationInfo.unAuthenticated() ).principals( RoleKeys.ADMIN ).build() )
            .build();
    }
}
