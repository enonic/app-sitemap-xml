/**
 * Keeps each sitemap as a node of a transient repository, named by the id of its key, with the sitemap files as attachments. A
 * transient repository is left out of dumps and snapshots, and its old versions are vacuumed early. Its binaries are in XP's blob store,
 * which all cluster nodes share, so a sitemap generated by one node is served by all.
 * <p>
 * Storing a sitemap again creates a new version of its node: requests still reading the files of the previous version keep reading them
 * until the version is vacuumed. Whether the content of the sitemap changed and whether it is being generated
 * are attributes of the current version, which are changed without creating a version.
 */
final class RepositorySitemapStore
    implements SitemapStore
{
    static final RepositoryId REPOSITORY = RepositoryId.from( "com.enonic.app.sitemapxml" );

    static final String OBSOLETE = "obsolete";

    static final String GENERATING = "generating";

    static final String QUEUED = "queued";

    static final String CHECKED = "checked";

    /**
     * Sent to all cluster nodes when a sitemap is found unchanged: version attributes change without a node event.
     */
    static final String CHECKED_EVENT = "sitemapxml.checked";

    private static final Logger LOG = LoggerFactory.getLogger( RepositorySitemapStore.class );

    private static final AccessControlList PERMISSIONS =
        AccessControlList.of( AccessControlEntry.create().principal( RoleKeys.ADMIN ).allowAll().build() );

    private static final PatternIndexConfigDocument INDEX_CONFIG = PatternIndexConfigDocument.create()
        .defaultConfig( IndexConfig.NONE )
        .add( "key.repository", IndexConfig.MINIMAL )
        .add( "key.branch", IndexConfig.MINIMAL )
        .add( "key.sitePath", IndexConfig.MINIMAL )
        .add( "key.principals", IndexConfig.MINIMAL )
        .add( "generatedAt", IndexConfig.MINIMAL )
        .build();

    private final NodeService nodeService;

    private final RepositoryService repositoryService;

    private final EventPublisher eventPublisher;

    private volatile boolean initialized;

    RepositorySitemapStore( final NodeService nodeService, final RepositoryService repositoryService, final EventPublisher eventPublisher )
    {
        this.nodeService = nodeService;
        this.repositoryService = repositoryService;
        this.eventPublisher = eventPublisher;
    }

    /**
     * Creates the repository unless it exists. Cluster nodes starting at the same time may both try.
     */
    private void initialize()
    {
        context().callWith( () -> {
            if ( repositoryService.get( REPOSITORY ) == null )
            {
                try
                {
                    repositoryService.createRepository( CreateRepositoryParams.create()
                                                            .repositoryId( REPOSITORY )
                                                            .transientFlag( true )
                                                            .rootPermissions( PERMISSIONS )
                                                            .build() );
                }
                catch ( RepositoryAlreadyExistsException e )
                {
                    LOG.debug( "Repository {} created by another node", REPOSITORY );
                }
            }
            return null;
        } );
    }

    @Override
    public @Nullable Stored load( final String id )
    {
        return call( () -> {
            final Node node = nodeService.getByPath( path( id ) );
            return node == null ? null : toStored( node );
        } );
    }

    @Override
    public boolean claimNew( final String id, final SitemapCache.Key key, final String member,
                             final Instant now )
    {
        return call( () -> {
            try
            {
                nodeService.create( CreateNodeParams.create()
                                        .parent( NodePath.ROOT )
                                        .name( id )
                                        .data( data( key, null, null, null, null ) )
                                        .indexConfigDocument( INDEX_CONFIG )
                                        .permissions( PERMISSIONS )
                                        .versionAttributesResolver(
                                            VersionAttributesResolver.of( generating( member, now ) ) )
                                        .refresh( RefreshMode.ALL )
                                        .build() );
                return true;
            }
            catch ( NodeAlreadyExistAtPathException e )
            {
                return false;
            }
        } );
    }

    @Override
    public boolean claim( final Stored stored, final String member, final Instant now, final Duration stale )
    {
        final Generating generating = stored.generating();
        if ( generating != null && !generating.member().equals( member ) && generating.since().plus( stale ).isAfter( now ) )
        {
            return false;
        }
        return call( () -> {
            final Node node = nodeService.getByPath( path( stored.id() ) );
            if ( node == null )
            {
                return false;
            }
            final Generating queued = stored.queued();
            apply( node.getNodeVersionId(), generating( member, now ),
                   queued != null && queued.member().equals( member ) ? QUEUED : null );
            return true;
        } );
    }

    @Override
    public boolean queue( final Stored stored, final String member, final Instant now, final Duration stale )
    {
        final Generating queued = stored.queued();
        if ( queued != null && queued.member().equals( member ) )
        {
            return true;
        }
        if ( queued != null && queued.since().plus( stale ).isAfter( now ) )
        {
            return false;
        }
        call( () -> {
            apply( NodeVersionId.from( stored.version() ), attribute( QUEUED, member, now ) );
            return null;
        } );
        return true;
    }

    @Override
    public Stored save( final String id, final SitemapCache.Key key, final Sitemap sitemap,
                        final @Nullable Instant validUntil, final Instant startedAt, final Instant now )
    {
        final Map<String, ByteSource> files = sitemap.storedFiles();
        final PropertyTree data = data( key, sitemap, validUntil, startedAt, now );
        files.keySet().forEach( name -> data.addBinaryReference( "file", reference( name ) ) );
        final VersionAttributesResolver noAttributes = VersionAttributesResolver.of( Attributes.create().build() );
        return call( () -> {
            final Node existing = nodeService.getByPath( path( id ) );
            final Node node;
            if ( existing == null )
            {
                final CreateNodeParams.Builder create = CreateNodeParams.create()
                    .parent( NodePath.ROOT )
                    .name( id )
                    .data( data )
                    .indexConfigDocument( INDEX_CONFIG )
                    .permissions( PERMISSIONS )
                    .versionAttributesResolver( noAttributes )
                    .refresh( RefreshMode.ALL );
                files.forEach( ( name, content ) -> create.attachBinary( reference( name ), content ) );
                node = nodeService.create( create.build() );
            }
            else
            {
                final UpdateNodeParams.Builder update = UpdateNodeParams.create()
                    .id( existing.id() )
                    .editor( editable -> editable.data = data )
                    .versionAttributesResolver( noAttributes )
                    .refresh( RefreshMode.ALL );
                files.forEach( ( name, content ) -> update.attachBinary( reference( name ), content ) );
                node = nodeService.update( update.build() );
                final Instant obsolete = obsolete( existing );
                if ( obsolete != null && !obsolete.isBefore( startedAt ) )
                {
                    apply( node.getNodeVersionId(),
                           Attributes.create().attribute( OBSOLETE, GenericValue.stringValue( obsolete.toString() ) ).build() );
                }
            }
            return toStored( node );
        } );
    }

    @Override
    public void release( final String id, final String member )
    {
        final Stored stored = load( id );
        if ( stored == null || stored.generating() == null || !stored.generating().member().equals( member ) )
        {
            return;
        }
        if ( stored.sitemap() == null )
        {
            delete( stored );
            return;
        }
        call( () -> {
            final Node node = nodeService.getByPath( path( id ) );
            if ( node != null )
            {
                apply( node.getNodeVersionId(), Attributes.create().build(), GENERATING );
            }
            return null;
        } );
    }

    @Override
    public @Nullable Stored check( final Stored stored, final String member, final Instant startedAt )
    {
        final Stored checked = call( () -> {
            final Node node = nodeService.getByPath( path( stored.id() ) );
            if ( node == null || !node.getNodeVersionId().toString().equals( stored.version() ) )
            {
                return null;
            }
            apply( node.getNodeVersionId(),
                   Attributes.create().attribute( CHECKED, GenericValue.stringValue( startedAt.toString() ) ).build(), GENERATING,
                   QUEUED );
            return toStored( node );
        } );
        if ( checked != null )
        {
            eventPublisher.publish( Event.create( CHECKED_EVENT ).distributed( true ).value( "id", stored.id() ).build() );
        }
        return checked;
    }

    @Override
    public void markObsolete( final Stored stored, final Instant now )
    {
        final Instant obsolete = stored.obsolete();
        if ( obsolete == null || obsolete.isBefore( now ) )
        {
            applyTo( stored, OBSOLETE, now );
        }
    }

    @Override
    public List<Stored> generatedOnRequestBefore( final Instant time )
    {
        return query( NodeQuery.create()
                          .parent( NodePath.ROOT )
                          .addQueryFilter( BooleanFilter.create().mustNot( filter( "key.principals", SitemapCache.Key.ANONYMOUS ) ).build() )
                          .addQueryFilter(
                              RangeFilter.create().fieldName( "generatedAt" ).lt( ValueFactory.newDateTime( time ) ).build() ) );
    }

    @Override
    public List<Stored> find( final String repositoryId, final @Nullable String branch )
    {
        final NodeQuery.Builder query =
            NodeQuery.create().parent( NodePath.ROOT ).addQueryFilter( filter( "key.repository", repositoryId ) );
        if ( branch != null )
        {
            query.addQueryFilter( filter( "key.branch", branch ) );
        }
        return query( query );
    }

    @Override
    public List<Stored> ofSite( final SitemapCache.Key key )
    {
        final NodeQuery.Builder query = NodeQuery.create()
            .parent( NodePath.ROOT )
            .addQueryFilter( filter( "key.repository", key.repositoryId() ) )
            .addQueryFilter( filter( "key.branch", key.branch() ) )
            .addQueryFilter( filter( "key.sitePath", key.params().sitePath() ) );
        key.principals().forEach( principal -> query.addQueryFilter( filter( "key.principals", principal ) ) );
        return query( query ).stream().filter( stored -> stored.key().principals().equals( key.principals() ) ).toList();
    }

    @Override
    public boolean delete( final Stored stored )
    {
        return call( () -> {
            final Node node = nodeService.getByPath( path( stored.id() ) );
            if ( node == null || !node.getNodeVersionId().toString().equals( stored.version() ) )
            {
                return false;
            }
            final Stored current = toStored( node );
            if ( !Objects.equals( current.generating(), stored.generating() ) || !Objects.equals( current.queued(), stored.queued() ) ||
                !Objects.equals( current.generatedAt(), stored.generatedAt() ) )
            {
                return false;
            }
            nodeService.delete( DeleteNodeParams.create().nodeId( node.id() ).refresh( RefreshMode.ALL ).build() );
            return true;
        } );
    }

    private List<Stored> query( final NodeQuery.Builder query )
    {
        return call( () -> {
            final List<Stored> stored = new ArrayList<>();
            for ( final Node node : nodeService.getByIds(
                nodeService.findByQuery( query.size( NodeQuery.ALL_RESULTS_SIZE_FLAG ).build() ).getNodeIds() ) )
            {
                stored.add( toStored( node ) );
            }
            return stored;
        } );
    }

    private Stored toStored( final Node node )
    {
        final PropertyTree data = node.data();
        final NodeVersion version = nodeService.getVersion( node.id(), node.getNodeVersionId() );
        final Attributes attributes =
            version == null || version.getAttributes() == null ? Attributes.create().build() : version.getAttributes();
        final SitemapCache.Key key = SitemapNodeData.readKey( data.getRoot() );
        final Sitemap sitemap = SitemapNodeData.readSitemap( data.getRoot(), files( node.id(), node.getNodeVersionId() ) );
        final Instant checked = instant( attributes, CHECKED );
        final Instant startedAt = later( data.getInstant( "startedAt" ), checked );
        final Instant obsolete = instant( attributes, OBSOLETE );
        return new Stored( node.name().toString(), node.getNodeVersionId().toString(), key,
                           sitemap, data.getInstant( "validUntil" ), startedAt,
                           later( data.getInstant( "generatedAt" ), checked ),
                           obsolete != null && startedAt != null && obsolete.isBefore( startedAt ) ? null : obsolete,
                           generation( attributes, GENERATING ), generation( attributes, QUEUED ) );
    }

    /**
     * When the version of the node was marked as obsolete, read after it was replaced, so a mark applied meanwhile is included.
     */
    private @Nullable Instant obsolete( final Node node )
    {
        final NodeVersion version = nodeService.getVersion( node.id(), node.getNodeVersionId() );
        return version == null || version.getAttributes() == null ? null : instant( version.getAttributes(), OBSOLETE );
    }

    private Sitemap.FileSource files( final NodeId nodeId, final NodeVersionId versionId )
    {
        return name -> new ByteSource()
        {
            @Override
            public InputStream openStream()
                throws IOException
            {
                return call( () -> nodeService.getBinary( nodeId, versionId, reference( name ) ) ).openStream();
            }
        };
    }

    private static PropertyTree data( final SitemapCache.Key key, final @Nullable Sitemap sitemap,
                                      final @Nullable Instant validUntil, final @Nullable Instant startedAt,
                                      final @Nullable Instant generatedAt )
    {
        final PropertyTree data = new PropertyTree();
        SitemapNodeData.writeKey( data.getRoot(), key );
        if ( sitemap != null )
        {
            SitemapNodeData.writeSitemap( data.getRoot(), sitemap );
        }
        if ( validUntil != null )
        {
            data.setInstant( "validUntil", validUntil );
        }
        if ( startedAt != null )
        {
            data.setInstant( "startedAt", startedAt );
        }
        if ( generatedAt != null )
        {
            data.setInstant( "generatedAt", generatedAt );
        }
        return data;
    }

    private void applyTo( final Stored stored, final String name, final Instant time )
    {
        call( () -> {
            apply( NodeVersionId.from( stored.version() ),
                   Attributes.create().attribute( name, GenericValue.stringValue( time.toString() ) ).build() );
            return null;
        } );
    }

    private void apply( final NodeVersionId versionId, final Attributes add, final @Nullable String... remove )
    {
        final ApplyVersionAttributesParams.Builder params =
            ApplyVersionAttributesParams.create().nodeVersionId( versionId ).addAttributes( add );
        final Set<String> removed = remove == null ? Set.of() : Arrays.stream( remove ).filter( Objects::nonNull ).collect(
            Collectors.toUnmodifiableSet() );
        if ( !removed.isEmpty() )
        {
            params.removeAttributes( removed );
        }
        nodeService.applyVersionAttributes( params.build() );
    }

    private static Attributes generating( final String member, final Instant now )
    {
        return attribute( GENERATING, member, now );
    }

    private static Attributes attribute( final String name, final String member, final Instant now )
    {
        return Attributes.create()
            .attribute( name, GenericValue.newObject().put( "member", member ).put( "since", now.toString() ).build() )
            .build();
    }

    private static @Nullable Generating generation( final Attributes attributes, final String name )
    {
        final GenericValue value = attributes.get( name );
        return value == null ? null : new Generating( value.property( "member" ).asString(),
                                                      Instant.parse( value.property( "since" ).asString() ) );
    }

    private static @Nullable Instant later( final @Nullable Instant time, final @Nullable Instant other )
    {
        return time == null || other != null && other.isAfter( time ) ? other : time;
    }

    private static @Nullable Instant instant( final Attributes attributes, final String name )
    {
        final GenericValue value = attributes.get( name );
        return value == null ? null : Instant.parse( value.asString() );
    }

    private static ValueFilter filter( final String field, final String value )
    {
        return ValueFilter.create().fieldName( field ).addValue( ValueFactory.newString( value ) ).build();
    }

    private static BinaryReference reference( final String name )
    {
        return BinaryReference.from( name + Sitemap.GZIP_EXTENSION );
    }

    private static NodePath path( final String id )
    {
        return new NodePath( "/" + id );
    }

    private <T> T call( final Callable<T> callable )
    {
        if ( !initialized )
        {
            synchronized ( this )
            {
                if ( !initialized )
                {
                    initialize();
                    initialized = true;
                }
            }
        }
        return context().callWith( callable );
    }

    private static Context context()
    {
        return ContextBuilder.create()
            .repositoryId( REPOSITORY )
            .branch( RepositoryConstants.MASTER_BRANCH )
            .authInfo( AuthenticationInfo.copyOf( AuthenticationInfo.unAuthenticated() ).principals( RoleKeys.ADMIN ).build() )
            .build();
    }
}
